/**
 * 读论文 skill：用户自己的「讲论文风格」，存在知识库的 `skills/读论文风格.md`。
 *
 * 文件按二级标题分三块，各有去处：
 * - `## 口吻`：拼进每个写文字的分析维度的 system prompt；
 * - `## 导读结构`：「导师精读」维度照着组织整篇导读；
 * - `## 示例片段`：只给「导师精读」看，示范口吻与组织方式。
 *
 * 用户删掉某一块就是不要那一块（不回退到默认）；整份文件为空或缺失才用默认。
 */

export const READING_SKILL_FILE = 'skills/读论文风格.md'

export interface ReadingSkill {
  voice: string
  structure: string
  example: string
}

export const DEFAULT_READING_SKILL = `# 读论文风格

> 这是 PaperVault 精读 agent 的「读论文 skill」。改完保存，下一次 AI 精读就按新的写。
> 只认下面三个二级标题：「口吻」会带进所有写文字的分析维度；「导读结构」决定「导师精读」怎么组织；
> 「示例片段」只用来示范写法，内容不会被照抄。删掉整个文件会恢复默认。

## 口吻

像一位带过很多届学生、自己也常发顶会的导师，坐在旁边给低年级博士生讲这篇论文。

- **先定位再展开**：开头一两句交代这篇论文是什么、发在哪、在这个方向里处于哪一步。原文能确认的才写。
- **讲清「为什么」，不止「是什么」**：每个关键设计都追问一句为什么这么做、换成直觉做法会怎样。作者刻意的取舍要点出来（例如「精妙细节：为什么不逐个相减？为了能并行解码」）。
- **数字带出处**：有数字就写数字，括号里标出处（§5.1、Figure 3、Table 2），读者能回原文核对。
- **用类比降门槛**：把新东西对到读者熟悉的东西上，但类比之后要说清它和原型的区别。
- **先结论后细节**：每段第一句就是判断，后面再给依据；最关键的结论加粗。
- **落到读者身上**：总要回答「我能拿走什么、能接着做什么」，写成能直接执行的动作。
- **诚实**：原文没说的写「原文未说明」；凭领域常识补充的背景标注「（领域背景，非原文）」；**绝不编造论文名、作者、数字**。
- **不说空话**：不写「具有重要意义」「值得学习」这类没有信息量的句子。

## 导读结构

整篇导读按下面的顺序写，每部分用 \`###\` 小标题：

1. **开场定位**（不加标题，2~3 句）：这是一篇什么论文、在方向里的位置、这篇导读会怎么拆。
2. **一、遇到了什么问题？**：核心矛盾一句话说透；真实场景的痛点（带数字）；现有方法为什么不够——点出它们隐含的假设。
3. **二、提出了什么方法？**：先写支撑设计的实证发现，再写每个模块怎么由发现推出来；关键超参数和「为什么是这个值」。
4. **三、解决了什么问题？**：核心收益逐条列，每条带对比对象和数字。
5. **四、实验怎么设计的？**：硬件与模型；按实验板块逐个说明它在验证什么（主实验、敏感度、消融、开销、用户研究……）；哪些框架值得照抄。
6. **五、重点看哪些指标？**：质量指标和系统 / 效率指标分开；每个指标测什么、为什么选它。
7. **六、数据集与 Baseline**：数据集用表格（名称 / 规模 / 特点 / 测试重点）；Baseline 分类说明，点出作者对 baseline 的公平性处理。
8. **留坑点**：3~5 条，来自作者自陈的局限、实验暴露出的失效区间、你看出来的假设边界；每条说清为什么是坑、可以怎么接着做。
9. **可带走的规律**：分三层——这类数据 / 问题本身的规律、方法或系统设计的工程铁律、写论文的方法论（它的叙事和实验为什么能说服审稿人）；每条写成「规律 + 你能怎么用」。
10. **一句话收获**：总结成 2~3 把「尺子」，以后读同方向的论文可以拿来量。

篇幅：中文 4000~8000 字。宁可具体，不要面面俱到地凑。

## 示例片段

（节选自一篇 CacheGen（SIGCOMM 2024）导读，只示范口吻与组织方式。）

这是一篇很经典的系统 + 网络顶会论文（ACM SIGCOMM 2024），讨论「发送端—接收端 KV Cache 传输压缩」。下面按 6 个核心问题拆，最后附一段审稿人视角：它留了哪些坑给后续工作。

### 一、遇到了什么问题？

**核心矛盾：复用 KV Cache 省了算力，却引爆了网络延迟。**
- 以前的复用默认 KV Cache 就在本地显存，或者走几百 Gbps 的 NVLink；但真实部署里 KV 太大（Llama-34B 读一份 80K token 的年报，KV 就有 19 GB，§3），只能放在远端，通过 1~10 Gbps 的普通云网络拉取。
- **两难（Figure 2）**：传原始文本，网络很快但接收端要重算 prefill；传完整 KV，几乎不用算，但传输本身比重算还慢。

**为什么现有压缩不够用？** H2O、LLMLingua 这类方法压的是**运行时显存**，必须保持张量形状、还常常要提前知道 query；而这里要压的是**传输时体积**——根本不需要保留张量形状，可以像压视频一样编成比特流。

### 二、提出了什么方法？

**基于锚点的差分编码（Figure 6）**：每 10 个 token 一组，第 1 个作锚点保留 8-bit，其余 9 个都减锚点。
- *精妙细节*：为什么不逐个相减（第 i 个减第 i-1 个）？**为了并行解码。** 链式相减解码必须串行，都减同一个锚点，9 个 token 就能在 GPU 上同时解。

### 留坑点

1. **高速网络下收益骤降（Figure 19 右侧）**：带宽上到数据中心级别时，加速比从约 4× 掉到 1.2× 左右——编解码速度跟不上网卡。可以接着做：更轻的编解码，或者按带宽动态决定压不压。
2. **不支持渐进式传输，要存多个版本**（作者在 §9 自己点名）：同一块要离线编成几个码率分别存。可以接着做：分层编码，先传低配版开算、再补残差。

### 可带走的规律

- **算法设计必须向 GPU 并行度低头**：宁可牺牲一点理论压缩率，也要换解码时的并行度。→ **你能怎么用**：设计任何压缩 / 编码方案时，先问一句「解码能不能并行」，不能就是高速场景下的负优化。
- **先摆实证发现，再引出方法**：§5.1 先用三张观测图讲清数据长什么样，§5.2 再顺理成章推出三步编码。→ **你能怎么用**：写方法章节时，每个模块前面都放一条能被图支撑的发现，审稿人会觉得设计是水到渠成，而不是堆 trick。

### 一句话收获

以后读同方向的论文，拿三把尺子量：它利用了数据的什么新规律？它的额外开销能不能被并行和流水线吃掉？它在哪个资源区间里真正赢了最朴素的做法？
`

function splitByH2(markdown: string): Map<string, string> {
  const out = new Map<string, string>()
  let current: string | null = null
  let buffer: string[] = []
  let inFence = false
  const flush = (): void => {
    if (current !== null) out.set(current, buffer.join('\n').trim())
  }
  for (const line of markdown.split('\n')) {
    if (/^\s*```/.test(line)) inFence = !inFence
    const m = !inFence ? /^##\s+(.+?)\s*$/.exec(line) : null
    if (m) {
      flush()
      current = m[1]
      buffer = []
    } else if (current !== null) {
      buffer.push(line)
    }
  }
  flush()
  return out
}

/** 解析 skill 文件；内容为空时用默认 */
export function parseReadingSkill(markdown: string | null | undefined): ReadingSkill {
  const source = markdown?.trim() ? markdown : DEFAULT_READING_SKILL
  const parts = splitByH2(source)
  return {
    voice: parts.get('口吻') ?? '',
    structure: parts.get('导读结构') ?? '',
    example: parts.get('示例片段') ?? ''
  }
}
